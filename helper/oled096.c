static unsigned char byteval;
static unsigned char scaled_line[100];

void oled_send_cmd(I2C_SLAVE_DESC *slave, int n, const unsigned char *data, int command, int repeat)
{
    if (slave == NULL || data == NULL || n <= 0)
        return;

    if (command) {
        /*
         * SSD1306 command stream:
         * 0x80 means "one command byte follows, more control bytes may follow".
         * Send each command as a small two-byte SDK transaction. This keeps the
         * code simple and avoids any fixed-size command buffer limit.
         */
        for (int i = 0; i < n; i++) {
            unsigned char packet[2] = { 0x80, data[i] };
            i2c_write_blocking(slave->i2c, slave->slave_7bit_addr, packet, sizeof(packet), false);
        }
    } else {
        /*
         * SSD1306 data stream:
         * one 0x40 control byte followed by display RAM data.
         * oled_clear_display() sends 128 repeated bytes, so 129 bytes is enough
         * for all current calls.
         */
        unsigned char packet[129];
        int remaining = n;
        const unsigned char *p = data;

        while (remaining > 0) {
            int chunk = remaining;
            if (chunk > 128)
                chunk = 128;

            packet[0] = 0x40;
            for (int i = 0; i < chunk; i++) {
                packet[i + 1] = repeat ? data[0] : p[i];
            }

            i2c_write_blocking(slave->i2c, slave->slave_7bit_addr, packet, (size_t)(chunk + 1), false);

            if (!repeat)
                p += chunk;
            remaining -= chunk;
        }
    }
}

void oled_set_xy(I2C_SLAVE_DESC *slave, int x, int y)
{
    unsigned char seq[3];

    x = x % 128;
    y = y % 64;
    seq[0] = 0xB0 + y / 8;  // Set page
    seq[1] = 0x00 + x % 16; // Set low part of start address
    seq[2] = 0x10 + x / 16; // Set high part

    oled_send_cmd(slave, sizeof(seq), seq, I2C_CMD, I2C_NO_REPEAT);
}

void oled_set_pixel_xy(I2C_SLAVE_DESC *slave, int x, int y)
{
    byteval = 1 << (y % 8);
    oled_set_xy(slave, x, y);
    oled_send_cmd(slave, 1, &byteval, I2C_DATA, I2C_NO_REPEAT);
}

void oled_set_byte_xy(I2C_SLAVE_DESC *slave, int x, int y, int b)
{
    byteval = (unsigned char)b;
    oled_set_xy(slave, x, y);
    oled_send_cmd(slave, 1, &byteval, I2C_DATA, I2C_NO_REPEAT);
}

void oled_gap(I2C_SLAVE_DESC *slave)
{
    unsigned char zero = 0;
    oled_send_cmd(slave, 1, &zero, I2C_DATA, I2C_NO_REPEAT);
}

void oled_display_int(I2C_SLAVE_DESC *slave, long int n, int num_digits)
{
    int mul = 10000;

    if (n < 0) {
        oled_display_string(slave, "-");
        n = -n;
    } else {
        oled_display_string(slave, " ");
    }

    for (int i = 5; i > 0; i--) {
        int dig = (int)(n / mul);
        n = n % mul;
        mul /= 10;

        if (i <= num_digits) {
            oled_send_cmd(slave, 5, font_5x7_letters + ('0' - ' ') * 5 + dig * 5,
                          I2C_DATA, I2C_NO_REPEAT);
            oled_gap(slave);
        }
    }
}

void oled_display_string(I2C_SLAVE_DESC *slave, const char *string)
{
    if (string == NULL)
        return;

    while (*string) {
        unsigned char ch = (unsigned char)*string++;

        if (ch < ' ' || ch > '~')
            ch = '?';

        oled_send_cmd(slave, 5, font_5x7_letters + (ch - ' ') * 5,
                      I2C_DATA, I2C_NO_REPEAT);
        oled_gap(slave);
    }
}

void oled_clear_display(I2C_SLAVE_DESC *slave)
{
    unsigned char zero = 0;

    for (int y = 0; y < 64; y += 8) {
        oled_set_xy(slave, 0, y);
        oled_send_cmd(slave, 128, &zero, I2C_DATA, I2C_REPEAT);
    }
}

void oled_display_scaled_string_xy(I2C_SLAVE_DESC *slave, const char *string, int x, int y, int scale)
{
    unsigned char i;
    int j, k, s;
    int scale_i;
    int b;
    int len;

    if (string == NULL || scale <= 0)
        return;

    len = (int)strlen(string);
    scale_i = 0;
    memset(scaled_line, 0, sizeof(scaled_line));

    for (k = 0; k < len; k++) {
        unsigned char ch = (unsigned char)string[k];

        if (ch < ' ' || ch > '~')
            ch = '?';

        for (i = 0; i < 5; i++) {
            for (j = 0; j < 8; j++) {
                b  = font_5x7_letters[(ch - ' ') * 5 + i];
                b &= (1 << (7 - j));
                b >>= (7 - j);

                for (s = 0; s < scale; s++) {
                    if ((scale_i / 8) < (int)sizeof(scaled_line)) {
                        scaled_line[scale_i / 8] <<= 1;
                        scaled_line[scale_i / 8] |= (unsigned char)b;
                    }
                    scale_i++;
                }
            }
        }

        for (s = 0; s < scale; s++) {
            if ((scale_i / 8) < (int)sizeof(scaled_line))
                scaled_line[scale_i / 8] = 0;
            scale_i += 8;
        }
    }

    for (j = 0; j < scale; j++) {
        oled_set_xy(slave, x, y + 8 * ((scale - 1) - j));
        for (i = 0; i < 5 * len * scale; i += scale) {
            for (s = 0; s < scale; s++) {
                if ((size_t)(i + j) < sizeof(scaled_line))
                    oled_send_cmd(slave, 1, &(scaled_line[i + j]), I2C_DATA, I2C_NO_REPEAT);
            }
        }
        oled_gap(slave);
    }
}

void oled_setup(I2C_SLAVE_DESC *slave)
{
    if (slave == NULL)
        return;

    uint baudrate = slave->baudrate ? slave->baudrate : (400 * 1000);

    i2c_init(slave->i2c, baudrate);
    gpio_set_function(slave->sda_pin, GPIO_FUNC_I2C);
    gpio_set_function(slave->scl_pin, GPIO_FUNC_I2C);
    gpio_pull_up(slave->sda_pin);
    gpio_pull_up(slave->scl_pin);

    sleep_ms(100);

    oled_send_cmd(slave, sizeof(init_seq2), init_seq2, I2C_CMD, I2C_NO_REPEAT);
    oled_clear_display(slave);
}
